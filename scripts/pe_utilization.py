#!/usr/bin/env python3
"""PE utilization of the GEMM accelerator (buildplan Phase H: "measured PE
utilization reported", §6.1: measured, not peak GOPS).

Utilization = useful MACs / (cycles x ROWS x COLS): the fraction of PE-cycles
that did a multiply of the GEMM, M*K*N of them.

  1. Measured: from a gemmtest board log (default the ARRAY_CDC = 0 board,
     docs/reports/gemmtest_board.txt), each job's CYCLES register (START to
     idle, read by the core) and the whole call (DMA in, job, DMA out, timed
     by the core's cycle counter). Only the first block of results is used
     (in a CDC log, run 1 with the array at the core clock). For a log
     without "cdc" in its name every job must equal job_cycles(), or the
     script stops.
  2. Model: sw/model/accel_model.py's job_cycles(), which every RTL test
     requires CYCLES to equal (ARRAY_CDC = 0, or the array at the core clock
     with the stream's fixed per-tile cost, see the note), over shapes up to
     the buffers' limits. Labelled as the model's.

Usage: scripts/pe_utilization.py [board log] > docs/reports/pe_utilization.txt
"""

from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "sw" / "model"))
import accel_model as am  # noqa: E402

ROWS = COLS = 16
BUF = 16384
PES = ROWS * COLS


def util(m, k, n, cycles):
    return m * k * n / (cycles * PES)


def board(path):
    jobs = []
    for line in Path(path).read_text().splitlines():
        if "array clock /" in line and jobs:
            break                                   # run 1 at the first clock only
        g = re.match(r"gemmtest: (\d+)x(\d+)x(\d+) ok, job (\d+) cycles, call (\d+), core (\d+)", line)
        if g:
            jobs.append(tuple(int(x) for x in g.groups()))
    if not jobs:
        sys.exit(f"no gemmtest job lines in {path}")
    return jobs


def fits(m, k, n):
    acc = am.Accel(ROWS, COLS, BUF)
    acc.m, acc.k, acc.n = m, k, n
    return acc.shape_ok()


def main():
    log = sys.argv[1] if len(sys.argv) > 1 else "docs/reports/gemmtest_board.txt"
    direct = "cdc" not in Path(log).name
    print(f"# PE utilization, {ROWS}x{COLS} array ({PES} PEs), generated by scripts/pe_utilization.py")
    print("# utilization = M*K*N / (cycles * 256)")
    print()
    print(f"## 1. Measured on the board ({log}, first run)")
    print("#  job  = the CYCLES register (START to idle); call = DMA in + job + DMA out,")
    print("#  core = the same GEMM on the core alone (RV32I, shift-add multiply)")
    print(f"{'shape':>10} {'MACs':>7} {'job':>6} {'model':>6} {'job util':>9} {'call':>7} {'call util':>10} {'core':>8}")
    for m, k, n, job, call, core in board(log):
        macs = m * k * n
        model = am.job_cycles(m, k, n, ROWS, COLS)
        if direct and job != model:
            sys.exit(f"{m}x{k}x{n}: board job {job} cycles, model {model}")
        print(f"{f'{m}x{k}x{n}':>10} {macs:>7} {job:>6} {model:>6} {util(m, k, n, job):>8.1%} "
              f"{call:>7} {util(m, k, n, call):>9.2%} {core:>8}")
    print()
    print("## 2. Model: job_cycles() (= the RTL's CYCLES at ARRAY_CDC = 0, every test)")
    print("#  per tile: ROWS cycles of weight load + 1 swap + M rows + LATENCY + 2 drain,")
    print(f"#  LATENCY = {am.latency(ROWS, COLS)}; tiles do not overlap. Shapes past a buffer are refused.")
    print(f"{'shape':>14} {'tiles':>5} {'cycles':>7} {'util':>6}")
    shapes = [(16, 16, 16), (64, 16, 16), (128, 16, 16), (256, 16, 16),
              (64, 64, 64), (128, 64, 32), (256, 64, 16), (128, 128, 32),
              (17, 17, 17), (100, 50, 30), (256, 1, 16), (1, 1024, 1)]
    for m, k, n in shapes:
        if not fits(m, k, n):
            print(f"{f'{m}x{k}x{n}':>14}  refused (buffers)")
            continue
        tiles = am.ceil_div(k, ROWS) * am.ceil_div(n, COLS)
        cyc = am.job_cycles(m, k, n, ROWS, COLS)
        print(f"{f'{m}x{k}x{n}':>14} {tiles:>5} {cyc:>7} {util(m, k, n, cyc):>6.1%}")
    over = ROWS + 1 + am.latency(ROWS, COLS) + 2
    print()
    print(f"# Bound: with K, N multiples of 16, utilization = M / (M + {over}) per tile")
    print(f"# (less the 3 shape-check cycles); the buffers cap M at {BUF // (4 * COLS)} "
          f"(C lines / N tiles), so at most {256 / (256 + over):.1%}.")
    print("# With ARRAY_CDC = 1 at equal clocks a tile costs 2*SYNC_STAGES + 1 cycles more")
    print("# (measurements.md, \"Array clock domain: model cost\").")


if __name__ == "__main__":
    main()
